/*
  Other names people commonly type, keyed by ISO code. Several are the names this
  list used before it moved to ISO short names -- "Democratic Republic of the
  Congo", "Vatican City", "Viet Nam" -- so a visitor stored under one of them is
  still recognised when their record is edited.
*/
