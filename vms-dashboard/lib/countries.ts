/**
 * The country list both registration forms pick from.
 *
 * ENGLISH SHORT NAMES, and not translated -- for the reason the printed badge is
 * not: the name chosen here is stored as-is, printed on the card in English and
 * grouped on in the reports. Picking from one list also normalises spelling, so
 * "Timor-Leste", "East Timor" and "timor leste" do not become three delegations
 * in the entrance report. That is why the desk form is held to it too.
 *
 * Imports nothing, so `node --test` can load it without a bundler.
 */
