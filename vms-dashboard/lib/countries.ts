  AE: ["UAE", "Emirates"],
  BA: ["Bosnia"],
  CD: ["DR Congo", "DRC", "Democratic Republic of the Congo", "Congo-Kinshasa", "Zaire"],
  CG: ["Republic of the Congo", "Congo-Brazzaville"],
